/* погода на 12 дней: тепло в начале, ближе к концу октября — снег и лёд; три подряд одинаковых дня не выпадают */
function rollWeather(){
  const out={};let a=null,b=null;
  for(let d=1;d<=12;d++){
    const cold=Math.max(0,(d-3)/9);
    const w={sun:2.2-cold,rain:2,fog:.9,snow:cold*1.5,ice:cold*1.8};
    if(d<=2){delete w.snow;delete w.ice}
    if(a&&a===b)delete w[a];
    const k=wpick(w);out[d]=k;b=a;a=k;
  }
  return out;
}
