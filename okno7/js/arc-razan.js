function razanConfirm(v,rule,st){
  const fixes={
    R_SIGN:()=>{v.docs.application.sig=v.docs.passport.sig;return 'Подпись? Да, это моя часть процесса. Сейчас распишусь.'},
    R_SIGMATCH:()=>{v.docs.application.sig=v.docs.passport.sig;return 'Агент воспроизвёл подпись по описанию. Зря. Вот моя настоящая.'},
    R_APPDATE:()=>{v.docs.application.date=G.today;return 'Дата осталась из кэша. Исправлю на сегодняшнюю. Вручную. Кэш после этого тоже исправлю.'},
    R_PASSNUM:()=>{v.docs.application.pass=v.docs.passport.pass;return 'Цифру перепутали при распознавании. Сверю с паспортом сам. Вот, исправил.'},
    R_SNILSNUM:()=>{v.docs.application.snils=v.docs.snils.num;return 'Подтянулся номер из тестового примера. Сверю с карточкой. Да, теперь мой.'}
  };
  const id=rule&&v.viol.includes(rule)?rule:v.viol[0];
  const fixed=id&&fixes[id]?fixes[id]():null;
  if(fixed){recheck(v);v.noted.delete(id)}
  if(!st.confirmed)st.confirmed=[];
  st.confirmed[v.step]=true;v.annex=razanAnnex(v.step,st);
  return{kind:fixed?'fix':'dodge',rule:id,refreshDocs:true,
    line:RAZAN_TEXT[v.step].ask+' '+(fixed||'Документы проверил. Заявление подтверждаю сам.'),expr:'neutral'};
}
function makeRazan(st,n){
  const T=RAZAN_TEXT[n],identity=st.identity;
  let intro=T.intro;
  if(n===1)intro=(st.res0==='ok'?'Разрешение ваше получили, систему запустили. ':st.res0==='no'
    ?'После вашего отказа проверял систему на локальном стенде. В ведомства ничего не отправляли. '
    :'Я Разан Гапиров, инженер по автоматизации налоговой отчётности. Испытываю подачу заявлений на локальном стенде. ')+T.intro;
  if(n===2&&!st.met)intro='Я Разан Гапиров, инженер-программист. Моя система оптимизировала работу и заблокировала мне доступ к собственному проекту. Нужно отозвать согласие на автоматическое управление. Лично.';
  const v=genVisitor({arch:'it',arc:'razan',named:true,noBribe:true,sex:'m',age:29,fio:['Гапиров','Разан','Маратович'],sig:1997,
    birth:identity?new Date(identity.birth):undefined,place:identity?identity.place:undefined,reg:identity?identity.reg:REGION[0],
    face:identity?identity.face:RAZAN_FACE,service:T.service,flaws:[],intro});
  // Сохраняем личность между визитами, а ошибки в заявлениях вносим уже после восстановления данных.
  if(!st.identity)st.identity={birth:v.birth.getTime(),pass:v.pass,snils:v.snilsNo,place:v.place,reg:v.reg,face:v.face,
    issued:v.docs.passport.issued.getTime(),until:v.docs.passport.until.getTime()};
  const p=st.identity;v.pass=p.pass;v.snilsNo=p.snils;
  Object.assign(v.docs.passport,{pass:p.pass,issued:new Date(p.issued),until:new Date(p.until)});
  v.docs.application.pass=p.pass;v.docs.application.snils=p.snils;
  if(v.docs.snils)v.docs.snils.num=p.snils;
  const flaws=n===0?['R_SIGN']:n===1?['R_APPDATE','R_PASSNUM','R_SNILSNUM','R_SIGN']:['R_SIGMATCH','R_PASSNUM','R_SIGN'];
  const flaw=n===0||chance(.6)?flaws.find(isActive):null;
  v.flaws=flaw&&RULES[flaw].inject(v)!==false?[flaw]:[];recheck(v);
  v.step=n;v.annex=razanAnnex(n,st);v.askAlways=true;v.askLabel='Подтвердить лично';v.askPrompt=T.question;
  v.onAsk=rule=>razanConfirm(v,rule,st);
  v.lines.plead=T.plead;v.lines.ok=T.ok;v.lines.no=T.no;
  return v;
}
