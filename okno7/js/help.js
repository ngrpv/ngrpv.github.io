/* информационное окно с кнопкой «Закрыть»; во время смены останавливает часы */
function infoModal(html,onClose){
  if(!$('#modal').hidden)return;
  const inShift=!!(W&&!$('#s-work').hidden);if(inShift)W.paused++;
  modal(html+'<div class="row"><button class="btn primary" data-m="ok">Закрыть</button></div>',()=>{if(inShift)W.paused--;onClose&&onClose()});
}
